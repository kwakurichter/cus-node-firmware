#include <assert.h>
#include <stdio.h>
#include <string.h>
#include "console_input.h"

static uint32_t now;

static void check_text(ConsoleMavlinkFilter *filter)
{
  const char *text = "1\r\nw\r\n@net 1\r\n@status\r\n";
  for (size_t i = 0; i < strlen(text); i++) {
    assert(!consoleConsumeMavlink(filter, text[i], now++));
  }
}

static void check_packet(ConsoleMavlinkFilter *filter, const uint8_t *packet, size_t size)
{
  for (size_t i = 0; i < size; i++) {
    assert(consoleConsumeMavlink(filter, packet[i], now++));
  }
  check_text(filter);
}

int main(void)
{
  ConsoleMavlinkFilter filter = {0};
  // Actual GCS heartbeats generated by pymavlink; sequence 100 is ASCII 'd',
  // the legacy console's EEPROM-reset command. Checksums are also binary input.
  const uint8_t v1[] = {0xfe,0x09,0x64,0xff,0xbe,0x00,0x00,0x00,0x00,0x00,0x06,0x08,0x00,0x04,0x03,0x20,0x34};
  const uint8_t v2[] = {0xfd,0x09,0x00,0x00,0x64,0xff,0xbe,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x06,0x08,0x00,0x04,0x03,0x5c,0xbd};
  const uint8_t signed_v2[] = {
    0xfd,0x09,0x01,0x00,0x64,0xff,0xbe,0x00,0x00,0x00,0x00,0x00,0x00,0x00,0x06,0x08,0x00,0x04,0x03,0xbb,0x45,
    0x00,0x00,0x00,0x00,0x00,0x00,0x00,0xbe,0xcd,0xce,0x97,0xc4,0x83
  };
  assert(memchr(v1, 'd', sizeof(v1)) != NULL);
  check_packet(&filter, v1, sizeof(v1));
  check_packet(&filter, v2, sizeof(v2));
  check_packet(&filter, signed_v2, sizeof(signed_v2));

  // Framing boundaries for every payload length, including signed maximum-size
  // packets. Embedded menu commands, newlines and magic bytes remain discarded.
  const uint8_t pattern[] = {'d','w','1','8','@','\r','\n',0xfd,0xfe,'#'};
  for (unsigned format = 0; format < 3; format++) {
    for (unsigned length = 0; length <= 255; length++) {
      uint8_t packet[280];
      size_t size = length + (format == 0 ? 8 : 12) + (format == 2 ? 13 : 0);
      for (size_t i = 0; i < size; i++) {
        packet[i] = pattern[i % sizeof(pattern)];
      }
      packet[0] = format == 0 ? 0xfe : 0xfd;
      packet[1] = length;
      if (format != 0) {
        packet[2] = format == 2 ? 1 : 0;
      }
      check_packet(&filter, packet, size);
    }
  }
  // Back-to-back packets need no line endings.
  for (unsigned i = 0; i < 10; i++) {
    for (size_t j = 0; j < sizeof(v2); j++) {
      assert(consoleConsumeMavlink(&filter, v2[j], now++));
    }
  }
  check_text(&filter);
  assert(consoleConsumeMavlink(&filter, 0xfd, now++));
  assert(consoleConsumeMavlink(&filter, 255, now++));
  now += 1001;
  check_text(&filter);
  // Tick wrap must not break an in-progress frame.
  now = UINT32_MAX - 5;
  check_packet(&filter, signed_v2, sizeof(signed_v2));
  puts("Console MAVLink v1/v2/signature framing, text recovery and tick-wrap tests passed");
  return 0;
}
